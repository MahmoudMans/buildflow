package com.buildflow.report.service;

import com.buildflow.shared.error.BusinessException;
import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.pdmodel.PDPage;
import org.apache.pdfbox.pdmodel.PDPageContentStream;
import org.apache.pdfbox.pdmodel.common.PDRectangle;
import org.apache.pdfbox.pdmodel.font.PDFont;
import org.apache.pdfbox.pdmodel.font.PDType1Font;
import org.apache.pdfbox.pdmodel.font.Standard14Fonts;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.text.Normalizer;
import java.time.Instant;
import java.util.ArrayList;
import java.util.List;

@Service
public class PdfReportService {

    private static final float MARGIN =
        48.0f;

    private static final float BODY_SIZE =
        9.5f;

    private static final float BODY_LEADING =
        13.0f;

    private static final float HEADING_SIZE =
        12.0f;

    private static final float TITLE_SIZE =
        18.0f;

    public byte[] render(
        String title,
        List<Section> sections
    ) {
        try (
            PDDocument document =
                new PDDocument()
        ) {
            Writer writer =
                new Writer(
                    document
                );

            try {
                writer.title(
                    title
                );

                writer.text(
                    "Generated by BuildFlow at "
                        + Instant.now()
                );

                writer.space(8);

                for (
                    Section section
                    : sections
                ) {
                    writer.heading(
                        section.heading()
                    );

                    for (
                        Entry entry
                        : section.entries()
                    ) {
                        writer.keyValue(
                            entry.label(),
                            entry.value()
                        );
                    }

                    for (
                        String line
                        : section.lines()
                    ) {
                        writer.text(line);
                    }

                    writer.space(8);
                }
            } finally {
                writer.close();
            }

            ByteArrayOutputStream output =
                new ByteArrayOutputStream();

            document.save(output);

            return output.toByteArray();

        } catch (IOException exception) {
            throw new BusinessException(
                HttpStatus.INTERNAL_SERVER_ERROR,
                "PDF_GENERATION_FAILED",
                "The PDF report could not be generated."
            );
        }
    }

    public record Entry(
        String label,
        String value
    ) {
    }

    public record Section(
        String heading,
        List<Entry> entries,
        List<String> lines
    ) {
        public static Section of(
            String heading,
            List<Entry> entries
        ) {
            return new Section(
                heading,
                entries,
                List.of()
            );
        }

        public static Section lines(
            String heading,
            List<String> lines
        ) {
            return new Section(
                heading,
                List.of(),
                lines
            );
        }
    }

    private static final class Writer
        implements AutoCloseable {

        private final PDDocument document;

        private final PDFont regular =
            new PDType1Font(
                Standard14Fonts
                    .FontName
                    .HELVETICA
            );

        private final PDFont bold =
            new PDType1Font(
                Standard14Fonts
                    .FontName
                    .HELVETICA_BOLD
            );

        private PDPage page;

        private PDPageContentStream stream;

        private float y;

        private Writer(
            PDDocument document
        ) throws IOException {
            this.document =
                document;

            newPage();
        }

        private void title(
            String value
        ) throws IOException {
            ensureSpace(34);

            writeWrapped(
                value,
                bold,
                TITLE_SIZE,
                22.0f
            );

            space(4);
        }

        private void heading(
            String value
        ) throws IOException {
            ensureSpace(28);

            writeWrapped(
                value,
                bold,
                HEADING_SIZE,
                17.0f
            );

            space(2);
        }

        private void keyValue(
            String key,
            String value
        ) throws IOException {
            String safeValue =
                value == null
                    ? "—"
                    : value;

            writeWrapped(
                key + ": " + safeValue,
                regular,
                BODY_SIZE,
                BODY_LEADING
            );
        }

        private void text(
            String value
        ) throws IOException {
            writeWrapped(
                value,
                regular,
                BODY_SIZE,
                BODY_LEADING
            );
        }

        private void space(
            float amount
        ) throws IOException {
            ensureSpace(amount);

            y -= amount;
        }

        private void writeWrapped(
            String text,
            PDFont font,
            float size,
            float leading
        ) throws IOException {

            String sanitized =
                sanitize(text);

            float width =
                page.getMediaBox()
                    .getWidth()
                    - (
                        MARGIN * 2
                    );

            List<String> lines =
                wrap(
                    sanitized,
                    font,
                    size,
                    width
                );

            for (String line : lines) {
                ensureSpace(leading);

                stream.beginText();

                stream.setFont(
                    font,
                    size
                );

                stream.newLineAtOffset(
                    MARGIN,
                    y
                );

                stream.showText(
                    line
                );

                stream.endText();

                y -= leading;
            }
        }

        private List<String> wrap(
            String text,
            PDFont font,
            float size,
            float maxWidth
        ) throws IOException {

            List<String> result =
                new ArrayList<>();

            String[] paragraphs =
                text.split(
                    "\\R",
                    -1
                );

            for (
                String paragraph
                : paragraphs
            ) {
                if (
                    paragraph.isBlank()
                ) {
                    result.add("");
                    continue;
                }

                StringBuilder line =
                    new StringBuilder();

                for (
                    String word
                    : paragraph.split(
                        "\\s+"
                    )
                ) {
                    String candidate =
                        line.isEmpty()
                            ? word
                            : line
                                + " "
                                + word;

                    float width =
                        font.getStringWidth(
                            candidate
                        )
                            / 1000.0f
                            * size;

                    if (
                        width > maxWidth
                        && !line.isEmpty()
                    ) {
                        result.add(
                            line.toString()
                        );

                        line =
                            new StringBuilder(
                                word
                            );
                    } else {
                        line =
                            new StringBuilder(
                                candidate
                            );
                    }
                }

                if (!line.isEmpty()) {
                    result.add(
                        line.toString()
                    );
                }
            }

            return result;
        }

        private void ensureSpace(
            float required
        ) throws IOException {
            if (
                y - required
                    < MARGIN
            ) {
                newPage();
            }
        }

        private void newPage()
            throws IOException {

            if (stream != null) {
                stream.close();
            }

            page =
                new PDPage(
                    PDRectangle.A4
                );

            document.addPage(
                page
            );

            stream =
                new PDPageContentStream(
                    document,
                    page
                );

            y =
                page.getMediaBox()
                    .getHeight()
                    - MARGIN;
        }

        @Override
        public void close()
            throws IOException {

            if (stream != null) {
                stream.close();

                stream = null;
            }
        }

        private String sanitize(
            String input
        ) {
            if (input == null) {
                return "";
            }

            String normalized =
                Normalizer.normalize(
                    input,
                    Normalizer.Form.NFKD
                )
                    .replaceAll(
                        "\\p{M}+",
                        ""
                    );

            StringBuilder output =
                new StringBuilder();

            normalized
                .codePoints()
                .forEach(
                    codePoint -> {
                        if (
                            codePoint == '\n'
                            || codePoint == '\r'
                        ) {
                            output.append(
                                '\n'
                            );
                        } else if (
                            codePoint >= 32
                            && codePoint <= 126
                        ) {
                            output.appendCodePoint(
                                codePoint
                            );
                        } else {
                            output.append(
                                '?'
                            );
                        }
                    }
                );

            return output.toString();
        }
    }
}
